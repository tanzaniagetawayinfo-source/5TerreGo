create or replace function public.track_poi_partner_event(
  target_poi_id bigint,
  target_event_type text,
  target_visitor_key text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if target_event_type not in ('profile_view', 'whatsapp_click') then
    raise exception 'Invalid event type';
  end if;

  if not exists (select 1 from public.pois where id = target_poi_id) then
    raise exception 'POI not found';
  end if;

  insert into public.poi_partner_events (poi_id, event_type, visitor_key)
  values (target_poi_id, target_event_type, left(nullif(trim(target_visitor_key), ''), 120));
end;
$$;

revoke all on function public.track_poi_partner_event(bigint, text, text) from public;
grant execute on function public.track_poi_partner_event(bigint, text, text) to anon, authenticated;

